UPDATE organization_city c
 JOIN organization_province p ON p.id=c.province_id
 JOIN organization_administrative_region r ON r.province_code=p.province_code
  AND r.kind='DIRECT_COUNTY' AND r.name=c.city_name
 LEFT JOIN organization_city canonical ON canonical.city_code=r.code AND canonical.id<>c.id
 SET c.city_code=r.code
 WHERE p.province_code IN ('110000','120000','310000','500000') AND canonical.id IS NULL;

INSERT INTO organization_city (id,province_id,city_code,city_name,enabled)
 SELECT UUID_TO_BIN(UUID()),p.id,r.code,r.name,TRUE FROM organization_administrative_region r
 JOIN organization_province p ON p.province_code=r.province_code
 WHERE r.kind='DIRECT_COUNTY' AND p.province_code IN ('110000','120000','310000','500000')
 AND NOT EXISTS (SELECT 1 FROM organization_city c WHERE c.city_code=r.code);
