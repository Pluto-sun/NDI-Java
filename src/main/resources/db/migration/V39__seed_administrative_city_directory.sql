-- 通过标准代码匹配既有组织，不改动项目和账号引用的标识。
UPDATE organization_province p JOIN organization_administrative_region r
 ON r.kind='PROVINCE' AND (p.province_code=r.code OR
 REGEXP_REPLACE(p.province_name,'(特别行政区|维吾尔自治区|壮族自治区|回族自治区|自治区|省|市)$','')=
 REGEXP_REPLACE(r.name,'(特别行政区|维吾尔自治区|壮族自治区|回族自治区|自治区|省|市)$',''))
 LEFT JOIN organization_province canonical ON canonical.province_code=r.code AND canonical.id<>p.id
 SET p.province_code=r.code,p.province_name=r.name WHERE canonical.id IS NULL;
INSERT INTO organization_province (id,province_code,province_name,enabled)
 SELECT UUID_TO_BIN(UUID()),r.code,r.name,TRUE FROM organization_administrative_region r
 WHERE r.kind='PROVINCE' AND NOT EXISTS (SELECT 1 FROM organization_province p
 WHERE p.province_code=r.code OR p.province_name=r.name);

CREATE TEMPORARY TABLE administrative_city_seed AS
 SELECT r.code,r.province_code,r.name FROM organization_administrative_region r
 WHERE r.kind<>'PROVINCE' OR r.code IN ('110000','120000','310000','500000','710000','810000','820000');
-- 已有自定义标识但名称确切匹配标准地市时补齐代码，保留原记录标识。
UPDATE organization_city c JOIN organization_province p ON p.id=c.province_id
 JOIN administrative_city_seed r ON r.province_code=p.province_code AND c.city_name=r.name
 LEFT JOIN organization_city canonical ON canonical.city_code=r.code AND canonical.id<>c.id
 SET c.city_code=r.code WHERE canonical.id IS NULL;
INSERT INTO organization_city (id,province_id,city_code,city_name,enabled)
 SELECT UUID_TO_BIN(UUID()),p.id,r.code,r.name,TRUE FROM administrative_city_seed r
 JOIN organization_province p ON p.province_code=r.province_code
 WHERE NOT EXISTS (SELECT 1 FROM organization_city c WHERE c.city_code=r.code);
DROP TEMPORARY TABLE administrative_city_seed;
